// Collects every offer/paintings/<CODE>/painting.json into offer/paintings.js (the page reads it, works from a file or a web host)
// and offer/paintings/index.json (a plain list). Run automatically by add-painting and the launcher.
const { fs, path, ROOT, PAINTINGS, readJson, writeJson } = require('./lib');
function build() {
  const all = {}, list = [];
  if (fs.existsSync(PAINTINGS)) for (const code of fs.readdirSync(PAINTINGS).sort()) {
    const f = path.join(PAINTINGS, code, 'painting.json');
    if (!fs.existsSync(f)) continue;
    const p = readJson(f);
    p.images = (p.images || []).map(i => 'paintings/' + code + '/' + i);
    if (p.video) p.video = 'paintings/' + code + '/' + p.video;
    all[code] = p;
    list.push({ code, title: p.title, priceGbp: p.priceGbp, image: p.images[0] || null, launched: !!p.deployment });
  }
  fs.writeFileSync(path.join(ROOT, 'offer', 'paintings.js'), '// Generated by tools/build-paintings.js. Do not edit; edit painting.json instead.\nwindow.ART_PAINTINGS = ' + JSON.stringify(all, null, 2) + ';\n', 'utf8');
  fs.mkdirSync(PAINTINGS, { recursive: true });
  writeJson(path.join(PAINTINGS, 'index.json'), list);
  return list;
}
if (require.main === module) { const l = build(); console.log('Built offer/paintings.js with ' + l.length + ' painting(s): ' + (l.map(x => x.code).join(', ') || 'none')); }
module.exports = { build };
